CREATE TABLE Leases (
    lease_id       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    tenant_id      NUMBER(10)   NOT NULL,
    property_id    NUMBER(10)   NOT NULL,
    apt_number     VARCHAR2(10) NOT NULL,
    start_date     DATE         NOT NULL,
    number_months  NUMBER(3)    NOT NULL,
    rate           NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_lease PRIMARY KEY (lease_id),
    CONSTRAINT fk_lease_tenant FOREIGN KEY (tenant_id) REFERENCES Tenants(tenant_id),
    CONSTRAINT fk_lease_apt FOREIGN KEY (property_id, apt_number)
        REFERENCES Apartments(property_id, apt_number),
    CONSTRAINT ck_lease_months CHECK (number_months BETWEEN 1 AND 36),
    CONSTRAINT ck_lease_rate CHECK (rate > 0),
    CONSTRAINT ck_lease_start CHECK (start_date = TRUNC(start_date)
                                     AND EXTRACT(DAY FROM start_date) <= 28)

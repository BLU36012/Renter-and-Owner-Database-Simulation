CREATE OR REPLACE VIEW Lease_Details AS
SELECT l.lease_id, l.tenant_id, l.property_id, l.apt_number, l.start_date,
       l.number_months, l.rate,
       ADD_MONTHS(l.start_date, l.number_months) - 1 AS end_date,
       m.leave_date, m.refund_amount,
       CASE
           WHEN m.refund_amount IS NOT NULL THEN 'Moved out'
           WHEN l.start_date > TRUNC(SYSDATE) THEN 'Upcoming'
           WHEN ADD_MONTHS(l.start_date, l.number_months) - 1 < TRUNC(SYSDATE) THEN 'Ended'
           WHEN m.leave_date < TRUNC(SYSDATE) THEN 'Ended'
           ELSE 'Current'
       END AS lease_status
FROM Leases l
LEFT JOIN Move_Outs m ON m.lease_id = l.lease_id;

CREATE OR REPLACE VIEW Current_Leases AS
SELECT * FROM Lease_Details WHERE lease_status = 'Current';

CREATE OR REPLACE VIEW Lease_Balances AS
SELECT lease_id, rate + pet_fees AS monthly_charge, charged AS total_charged, owed AS total_owed,
       paid AS total_paid, charged - paid AS balance_due,
       CASE WHEN n < number_months THEN ADD_MONTHS(start_date, n) END AS next_due_date
FROM (SELECT x.*,
             NVL((SELECT SUM(p.monthly_fee) FROM Pets p WHERE p.lease_id = x.lease_id), 0) AS pet_fees,
             x.n * x.rate + NVL((SELECT SUM(p.monthly_fee * GREATEST(0, x.n
                 - GREATEST(0, CEIL(MONTHS_BETWEEN(p.added_date, x.start_date)))))
                 FROM Pets p WHERE p.lease_id = x.lease_id), 0) AS charged,
             x.number_months * x.rate + NVL((SELECT SUM(p.monthly_fee * GREATEST(0, x.number_months
                 - GREATEST(0, CEIL(MONTHS_BETWEEN(p.added_date, x.start_date)))))
                 FROM Pets p WHERE p.lease_id = x.lease_id), 0) AS owed,
             NVL((SELECT SUM(pay.amount) FROM Payments pay WHERE pay.lease_id = x.lease_id), 0) AS paid
      FROM (SELECT lease_id, rate, start_date, number_months,
                   CASE WHEN TRUNC(SYSDATE) < start_date THEN 0
                        ELSE LEAST(number_months, FLOOR(MONTHS_BETWEEN(TRUNC(SYSDATE), start_date)) + 1) END AS n
            FROM Leases) x);

CREATE OR REPLACE TRIGGER trg_lease_locked
BEFORE UPDATE OR DELETE ON Leases
BEGIN
    RAISE_APPLICATION_ERROR(-20001,
        'A lease cannot be changed or canceled once it is signed. Sign a new lease instead.');
END;
/

CREATE OR REPLACE TRIGGER trg_payment_locked
BEFORE UPDATE OR DELETE ON Payments
BEGIN
    RAISE_APPLICATION_ERROR(-20002, 'Recorded payments cannot be changed or deleted.');
END;
/

CREATE OR REPLACE TRIGGER trg_lease_needs_visit
BEFORE INSERT ON Leases
FOR EACH ROW
DECLARE
    v_visits NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_visits FROM Visits
     WHERE tenant_id = :NEW.tenant_id AND property_id = :NEW.property_id AND apt_number = :NEW.apt_number;
    IF v_visits = 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'This person must visit the apartment before signing a lease for it.');
    END IF;
END;

CREATE TABLE Properties (
    property_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    street         VARCHAR2(120) NOT NULL,
    city           VARCHAR2(60)  NOT NULL,
    state          CHAR(2)       NOT NULL,
    zip            VARCHAR2(10)  NOT NULL,
    property_cost  NUMBER(12,2),
    CONSTRAINT pk_properties PRIMARY KEY (property_id),
    CONSTRAINT uq_property_address UNIQUE (street, city, state),
    CONSTRAINT ck_property_state CHECK (REGEXP_LIKE(state, '^[A-Z]{2}$')),
    CONSTRAINT ck_property_zip CHECK (REGEXP_LIKE(zip, '^[0-9]{5}(-[0-9]{4})?$')),
    CONSTRAINT ck_property_cost CHECK (property_cost IS NULL OR property_cost >= 0)
);

CREATE TABLE Apartments (
    property_id       NUMBER(10)   NOT NULL,
    apt_number        VARCHAR2(10) NOT NULL,
    rent              NUMBER(10,2) NOT NULL,
    security_deposit  NUMBER(10,2) NOT NULL,
    square_feet       NUMBER(7,1),
    bedroom_amount    NUMBER(2)    NOT NULL,
    bathroom_amount   NUMBER(3,1)  NOT NULL,
    CONSTRAINT pk_apartments PRIMARY KEY (property_id, apt_number),
    CONSTRAINT fk_apt_property FOREIGN KEY (property_id)
        REFERENCES Properties(property_id) ON DELETE CASCADE,
    CONSTRAINT ck_apt_rent CHECK (rent > 0),
    CONSTRAINT ck_apt_deposit CHECK (security_deposit >= 0),
    CONSTRAINT ck_apt_sqft CHECK (square_feet IS NULL OR square_feet > 0),
    CONSTRAINT ck_apt_bedrooms CHECK (bedroom_amount BETWEEN 0 AND 10),
    CONSTRAINT ck_apt_bathrooms CHECK (bathroom_amount BETWEEN 1 AND 10
                                       AND MOD(bathroom_amount * 2, 1) = 0)
);

CREATE TABLE Amenities (
    amenity_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    property_id   NUMBER(10)    NOT NULL,
    amenity_name  VARCHAR2(100) NOT NULL,
    category      VARCHAR2(30)  NOT NULL,
    is_included   CHAR(1) DEFAULT 'Y' NOT NULL,
    monthly_fee   NUMBER(8,2) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_amenities PRIMARY KEY (amenity_id),
    CONSTRAINT fk_amenity_property FOREIGN KEY (property_id)
        REFERENCES Properties(property_id) ON DELETE CASCADE,
    CONSTRAINT uq_amenity_name UNIQUE (property_id, amenity_name),
    CONSTRAINT ck_amenity_included CHECK (is_included IN ('Y', 'N')),
    CONSTRAINT ck_amenity_fee CHECK ((is_included = 'Y' AND monthly_fee = 0)
                                     OR (is_included = 'N' AND monthly_fee > 0))
);

CREATE TABLE Apartment_Amenities (
    property_id   NUMBER(10)    NOT NULL,
